//! Exact raw-worker exceptions. Lines are intentionally not part of the key.

use super::source_scanner::Site;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum Category {
    Read,
    Deferred,
    Process,
    Root,
}

#[derive(Debug)]
pub(super) struct Entry {
    pub file: &'static str,
    pub item: &'static str,
    pub primitive: &'static str,
    pub fingerprint: u64,
    pub occurrence: usize,
    pub category: Category,
    pub reason: &'static str,
}

impl Entry {
    pub fn matches(&self, site: &Site) -> bool {
        self.file == site.file
            && self.item == site.item
            && self.primitive == site.primitive
            && self.fingerprint == site.fingerprint
            && self.occurrence == site.occurrence
    }
}

